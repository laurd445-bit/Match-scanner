async function processImage() {
  const input = document.getElementById('imageInput');
  const status = document.getElementById('status');
  const output = document.getElementById('output');

  if (!input.files || input.files.length === 0) {
    status.textContent = "Please select an image file first.";
    return;
  }

  const file = input.files[0];
  status.textContent = "Processing screenshot...";
  output.textContent = "";

  try {
    const ret = await Tesseract.recognize(
      file,
      'eng',
      {
        logger: m => {
          if (m.status === 'recognizing text') {
            status.textContent = `Scanning: ${Math.round(m.progress * 100)}%`;
          } else {
            status.textContent = m.status;
          }
        }
      }
    );

    const rawText = ret.data.text;
    const analysisResult = parseAndSelectOverallTopTwo(rawText);
    
    status.textContent = "Scan complete!";
    output.textContent = analysisResult;
  } catch (error) {
    status.textContent = "Error scanning image.";
    output.textContent = error.message || "Unable to parse image file.";
  }
}

function parseAndSelectOverallTopTwo(text) {
  // Extract all odds formatted as decimal numbers (e.g., 1.93, 3.84, 3.67)
  const oddsMatches = text.match(/\b\d\.\d{2}\b/g);
  
  if (!oddsMatches || oddsMatches.length < 3) {
    return "Could not detect valid 1X2 odds in the screenshot. Ensure match odds are clearly visible.";
  }

  // Group detected odds into 3-tuples corresponding to 1X2 market (Home, Draw, Away)
  const matches = [];
  for (let i = 0; i + 2 < oddsMatches.length; i += 3) {
    const homeOdds = parseFloat(oddsMatches[i]);
    const drawOdds = parseFloat(oddsMatches[i + 1]);
    const awayOdds = parseFloat(oddsMatches[i + 2]);
    matches.push({ homeOdds, drawOdds, awayOdds });
  }

  // Store every individual prediction across ALL matches
  const allPredictions = [];

  matches.forEach((m, idx) => {
    // 1. Calculate raw implied probabilities
    const rawHome = 1 / m.homeOdds;
    const rawDraw = 1 / m.drawOdds;
    const rawAway = 1 / m.awayOdds;
    const totalImplied = rawHome + rawDraw + rawAway;

    // 2. Calculate fair probabilities (removing house edge)
    const fairHome = (rawHome / totalImplied) * 100;
    const fairDraw = (rawDraw / totalImplied) * 100;
    const fairAway = (rawAway / totalImplied) * 100;

    // Add individual outcomes to global list
    allPredictions.push({
      matchNum: idx + 1,
      type: "Home Win (1)",
      odds: m.homeOdds,
      prob: fairHome
    });
    allPredictions.push({
      matchNum: idx + 1,
      type: "Straight Draw (X)",
      odds: m.drawOdds,
      prob: fairDraw
    });
    allPredictions.push({
      matchNum: idx + 1,
      type: "Away Win (2)",
      odds: m.awayOdds,
      prob: fairAway
    });
  });

  // Sort ALL predictions across all matches from highest probability to lowest
  allPredictions.sort((a, b) => b.prob - a.prob);

  // Grab the absolute Top 2 picks out of all uploaded matches
  const topPick1 = allPredictions[0];
  const topPick2 = allPredictions[1];

  let report = `=== TOP 2 HIGHEST PROBABILITY PICKS OVERALL ===\n`;
  report += `(Evaluated across all ${matches.length} uploaded matches)\n\n`;

  report += `🔥 PICK #1:\n`;
  report += `  • Match #${topPick1.matchNum} — ${topPick1.type}\n`;
  report += `  • Odds: ${topPick1.odds}\n`;
  report += `  • Fair Probability: ${topPick1.prob.toFixed(1)}%\n\n`;

  report += `🔥 PICK #2:\n`;
  report += `  • Match #${topPick2.matchNum} — ${topPick2.type}\n`;
  report += `  • Odds: ${topPick2.odds}\n`;
  report += `  • Fair Probability: ${topPick2.prob.toFixed(1)}%\n\n`;

  report += `========================================\n`;
  report += `FULL BREAKDOWN OF ALL MATCHES scanned:\n`;
  report += `========================================\n\n`;

  matches.forEach((m, idx) => {
    const rawHome = 1 / m.homeOdds;
    const rawDraw = 1 / m.drawOdds;
    const rawAway = 1 / m.awayOdds;
    const totalImplied = rawHome + rawDraw + rawAway;

    const fairHome = (rawHome / totalImplied) * 100;
    const fairDraw = (rawDraw / totalImplied) * 100;
    const fairAway = (rawAway / totalImplied) * 100;

    report += `Match #${idx + 1} Odds [1: ${m.homeOdds}] [X: ${m.drawOdds}] [2: ${m.awayOdds}]\n`;
    report += `  ➜ Fair Probabilities: Home: ${fairHome.toFixed(1)}% | Draw: ${fairDraw.toFixed(1)}% | Away: ${fairAway.toFixed(1)}%\n\n`;
  });

  report += "Note: Virtual football results are generated by server-side RNG algorithms and cannot be guaranteed.";
  return report;
      }
    
